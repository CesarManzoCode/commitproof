#!/usr/bin/env python3
"""k7-report-excerpt.py — the report excerpt of a finding package (CONTRACT
§11.4): faults, decided rules, leader changes, per-gateway unavailability
windows and latency per phase from the data block of cpreport's page of the
package's original run (K6, ADR-0036), and the checkers' result from its
checks.json. It reads only those two files and the render record's summary;
the page itself is regenerated byte for byte by the render command (K6.1).

With the run's observations.jsonl (extracted from its archive) it adds
each node's WAL position and role from the pooler-status observations
(polled every P24 = 1 s; observations only, ADR-0016) around every fault.

usage: k7-report-excerpt.py <page.html> <checks.json> <render-record-name> <render-stdout> <archive> [<observations.jsonl>]
"""
import json
import re
import sys


def secs(ns):
    """Nanoseconds as seconds with three decimals (integer arithmetic)."""
    if ns is None:
        return "—"
    ms = (ns + 500_000) // 1_000_000
    return f"{ms // 1000}.{ms % 1000:03d} s"


def msec(ns):
    if ns is None:
        return "—"
    us = (ns + 500) // 1000
    return f"{us // 1000}.{us % 1000:03d}"


def lsn(s):
    """A PostgreSQL LSN 'X/Y' as an integer (None if absent)."""
    if not s or "/" not in s:
        return None
    hi, lo = s.split("/")
    return (int(hi, 16) << 32) | int(lo, 16)


def wal_section(path, faults):
    """WAL positions and roles per node from pooler-status observations."""
    samples = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            o = json.loads(line)
            v = o.get("value") or {}
            if v.get("src") != "pooler-status" or not v.get("ok"):
                continue
            dec = v.get("decision") or {}
            rule = f"{dec.get('coordinator_term', '?')}.{dec.get('leader_subterm', '?')}" if dec else "—"
            samples.setdefault(v["node"], []).append((o["t"], v.get("wal_position") or "", v.get("pooler_type") or "", rule))
    w = ["", "## WAL positions and roles (pooler-status observations, 1 s polling)", "",
         "Each cell: the node's last successful pooler-status sample at or before the instant (role, decided rule it reports, WAL position). "
         "Observations only (ADR-0016); the runner reaches every node's pooler except those a fault isolates from it (LIM-28).", ""]
    for flt in faults:
        ph = flt.get("phases", {})
        instants = [("before inject", ph.get("inject")), ("confirmed", ph.get("confirmed")), ("heal", ph.get("heal")),
                    ("healed + 10 s", (ph.get("healed") or 0) + 10_000_000_000 if ph.get("healed") else None)]
        w.append(f"Fault {flt['id']} ({flt['kind']} on {', '.join(flt.get('targets') or [])}):")
        w.append("")
        w.append("| Node | " + " | ".join(f"{n} ({secs(t)})" for n, t in instants if t is not None) + " |")
        w.append("|---|" + "---|" * sum(1 for _, t in instants if t is not None))
        for node in sorted(samples):
            cells = []
            for _, t in instants:
                if t is None:
                    continue
                last = None
                for s in samples[node]:
                    if s[0] <= t:
                        last = s
                cells.append(f"{last[2]} {last[3]} `{last[1]}` ({secs(last[0])})" if last else "—")
            w.append(f"| {node} | " + " | ".join(cells) + " |")
        w.append("")
    # Role changes per node.
    ch = []
    for node in sorted(samples):
        prev = None
        for t, pos, typ, rule in samples[node]:
            if prev is not None and typ != prev:
                ch.append(f"{node} {prev} → {typ} first seen {secs(t)} (rule {rule}, WAL `{pos}`)")
            prev = typ
    if ch:
        w.append("Role changes: " + "; ".join(ch) + ".")
        w.append("")
    # The largest WAL position each node reported.
    w.append("Highest WAL position each node reported: " + "; ".join(
        f"{n} `{max((s for s in samples[n] if lsn(s[1]) is not None), key=lambda s: lsn(s[1]))[1]}`" for n in sorted(samples)
        if any(lsn(s[1]) is not None for s in samples[n])) + ".")
    return w


def main():
    page, checks, rec, stdout, archive = sys.argv[1:6]
    obs = sys.argv[6] if len(sys.argv) > 6 else None
    html = open(page, encoding="utf-8").read()
    m = re.search(r'<script type="application/json" id="cp-data"[^>]*>(.*?)</script>', html, re.S)
    if not m:
        sys.exit("no cp-data block in " + page)
    d = json.loads(m.group(1))
    c = json.load(open(checks, encoding="utf-8"))
    summary = json.loads(open(stdout, encoding="utf-8").read().strip().splitlines()[-1])
    out = summary["outputs"][0]
    if d["run_id"] != c["run_id"] or d["seal_root"] != c["seal_root"]:
        sys.exit("page and checks.json are of different runs")
    w = []
    p = w.append
    p(f"# Report excerpt — run `{d['run_id']}`")
    p("")
    p(f"From cpreport's page of the original run: `bin/cpreport render {archive} --out <dir>` "
      f"(record `{rec}` in `evidence/K7/commands.jsonl`) wrote `{out['file']}` "
      f"({out['bytes']} bytes, sha256 `{out['sha256']}`); the page is byte-reproducible (K6.1) and is not committed. "
      f"Seal root `{d['seal_root']}`; cpcheck's verdict **{c['verdict']}**; {d['history_lines']} history lines, "
      f"{d['operations']} operations. Faults, rules and leader changes are observations (ADR-0016): they never decide a verdict.")
    p("")
    p("## Faults")
    p("")
    p("| Fault | Kind | Targets | Injected | Confirmed | Heal | Healed | Rule changes | Leader changes |")
    p("|---|---|---|---|---|---|---|---|---|")
    for f in d["faults"]:
        ph = f.get("phases", {})
        rules = ", ".join(f.get("rules") or [])
        p(f"| {f['id']} | {f['kind']} | {', '.join(f.get('targets') or [])} | {secs(ph.get('inject'))} | {secs(ph.get('confirmed'))} | "
          f"{secs(ph.get('heal'))} | {secs(ph.get('healed'))} | {f.get('rule_changes', 0)}{' (' + rules + ')' if rules else ''} | {f.get('leader_changes', 0)} |")
    p("")
    p("## Decided rules and leader changes (observations)")
    p("")
    p("| Rule | Leader | Cohort | First seen |")
    p("|---|---|---|---|")
    for r in d["rules"]:
        p(f"| {r['rule']} | {r['leader']} | {', '.join(r['cohort'])} | {secs(r['first_seen'])} |")
    if d["leader_changes"]:
        p("")
        p("Leader changes: " + "; ".join(f"{x['from']} → {x['to']} at rule {x['rule']}, first seen {secs(x['t'])}" for x in d["leader_changes"]) + ".")
    if obs:
        w.extend(wal_section(obs, d["faults"]))
    p("")
    p("## Unavailability windows per gateway (ADR-0036)")
    p("")
    p("| Fault | Gateway | Window | Start | End | Length | Non-ok operations |")
    p("|---|---|---|---|---|---|---|")
    for f in d["faults"]:
        for gw in sorted(f.get("gateways") or {}):
            g = f["gateways"][gw]
            p(f"| {f['id']} | {gw} | {g.get('window', '—')} | {secs(g.get('window_start'))} | {secs(g.get('window_end'))} | "
              f"{secs(g.get('window_ns'))} | {g.get('non_ok', 0)} |")
    p("")
    p("## Latency per phase (ms)")
    p("")
    p("| Fault | Phase | Operations | p50 | p95 | p99 |")
    p("|---|---|---|---|---|---|")
    for f in d["faults"]:
        for ph in ("before", "during", "after"):
            x = (f.get("latency") or {}).get(ph)
            if x:
                p(f"| {f['id']} | {ph} | {x['n']} | {msec(x.get('p50'))} | {msec(x.get('p95'))} | {msec(x.get('p99'))} |")
    p("")
    p("## Checkers (cpcheck, `checks.json`)")
    p("")
    p("| Checker | Valid | Anomaly classes (count) |")
    p("|---|---|---|")
    for ch in c["checkers"]:
        counts = (ch.get("stats") or {}).get("counts") or {}
        cl = ", ".join(f"`{k}` ({v})" for k, v in sorted(counts.items()) if v) if ch["valid"] is False else "—"
        p(f"| {ch['id']} | {str(ch['valid']).lower()} | {cl} |")
    for ch in c["checkers"]:
        if ch["valid"] is not False:
            continue
        p("")
        p(f"First anomalies of {ch['id']} (cpcheck lists at most 20 per class):")
        p("")
        seen = {}
        for a in ch.get("anomalies") or []:
            seen[a["class"]] = seen.get(a["class"], 0) + 1
            if seen[a["class"]] > 3:
                continue
            p(f"- `{a['class']}` (ops {', '.join(str(o) for o in a.get('ops') or [])}): {a.get('explanation', '')}")
    sys.stdout.write("\n".join(w) + "\n")


if __name__ == "__main__":
    main()
