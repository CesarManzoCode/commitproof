#!/usr/bin/env bash
# k5-evidence.sh — produces evidence/K5 for gate K5 (CONTRACT §15 K5). Every
# command the gate reads runs through scripts/record-command.sh (argv, exit
# code, stdout/stderr sha256 in evidence/K5/commands.jsonl). Resumable like
# k4-evidence.sh: a step whose record already exists with an accepted exit
# code is skipped; an interrupted step (logs, no record) is retried under the
# next name; the campaign itself is resumable (sealed runs are never
# recomputed). Run from the repository root on a committed tree, one cluster
# at a time.
#
# usage: k5-evidence.sh setup|images|rebuild|campaign|d3p|oracle|analysis|ci|store|gate
#   setup     K5.1 before any live K5 run: binaries, precondition (cpgate
#             K1–K4 on copies), the K5 and K2 corpora regenerated byte for
#             byte and classified by cpcheck, every C7–C9 checker sabotage on
#             the K5 corpus, no sabotage symbols in product binaries. Corpus
#             results are stored zstd-compressed (P25); cpgate ties each to
#             its record by the summary's results_sha256.
#   images    binaries and the real images (runner rebuilt from this commit), verified,
#             and the mutants M3, M5 (isolation checked by the build, K4.4)
#   rebuild   after a harness fix: binaries and the real images rebuilt,
#             recorded as build-<n>, images-build-<n>, images-verify-<n>
#   campaign  campaigns/k5.json into evidence/K5/runs (hours; background)
#   d3p       campaigns/k5-d3p.json (D3′ on M3 and on the real build, ADR-0033)
#             into evidence/K5/runs, after the predictions commit; resumable
#             as campaign (campaign-k5-d3p, campaign-k5-d3p-2, …)
#   oracle    elle-cli cross-check of every real-build FAIL with C3 anomalies
#   analysis  diagnosis records for NOTES (observations, never verdicts):
#             k3obs (faults, leader changes, client gaps) and k5obs (LISTEN
#             loss windows, slot readiness, consumer reconnects, overload)
#             over the primary run directories, before store archives them
#   ci        make lint-workflow; make ci-unit ci-checkers ci-cluster-smoke
#             ci-nemesis-smoke ci-mutant-smoke (a new attempt after a rebuild)
#   store     runs archived in full or as stubs (ADR-0030), committed stubs
#             that ADR-0030 keeps in full replaced by their full archives
#             (ADR-0034), patches and lock copied, results.json written;
#             refuses to exceed P25 (250 MB). K5_STORE_POLICY selects
#             k5-store-runs.sh's policy (default adr0030)
#   gate      cpgate K5 --negative-controls (cpgate-k5, cpgate-k5-2, …)
set -u -o pipefail
export GOTOOLCHAIN=go1.26.9 CGO_ENABLED=0
EV=evidence/K5
REC=(scripts/record-command.sh "$EV/commands.jsonl" "$EV/logs")
mkdir -p "$EV/runs" "$EV/logs"

recorded() { # name → exit code of its record, or empty
	[ -f "$EV/commands.jsonl" ] || return 0
	grep -F "\"name\":\"$1\"" "$EV/commands.jsonl" | tail -n 1 | sed -n 's/.*"exit_code":\([0-9]*\).*/\1/p'
}
interrupted() { # name → true when its logs exist without a record
	[ -z "$(recorded "$1")" ] && { [ -e "$EV/logs/$1.stdout" ] || [ -e "$EV/logs/$1.stderr" ]; }
}
next() { # base → the first unrecorded, uninterrupted name of base, base-2, …
	local name=$1 n=1
	while [ -n "$(recorded "$name")" ] || interrupted "$name"; do n=$((n + 1)); name="$1-$n"; done
	echo "$name"
}
line() { # extended regexp of record names → line number of the last such record, or 0
	grep -nE "\"name\":\"($1)\"" "$EV/commands.jsonl" 2>/dev/null | tail -n 1 | cut -d: -f1 | grep . || echo 0
}
rundirs() { # unarchived sealed run directories under runs/
	local d
	for d in "$EV"/runs/*/; do
		[ -f "$d/seal.json" ] && echo "$d"
	done
	return 0
}
step() { # expected-exit|any name argv...
	local want=$1 name=$2 prev
	shift 2
	prev=$(recorded "$name")
	if [ -n "$prev" ]; then
		if [ "$want" = any ] || [ "$prev" -eq "$want" ]; then
			echo "== skip $name (recorded, exit $prev)" >&2
			return 0
		fi
		echo "k5-evidence: $name is recorded with exit $prev, expected $want; inspect $EV/logs/$name.*" >&2
		exit 1
	fi
	if interrupted "$name"; then
		echo "k5-evidence: $name was interrupted (logs, no record); move its logs aside or re-run under a new name" >&2
		exit 1
	fi
	echo "== $(date -u +%H:%M:%S) $name: $*" >&2
	"${REC[@]}" "$name" -- "$@" >/dev/null
	local rc=$?
	if [ "$want" != any ] && [ "$rc" -ne "$want" ]; then
		echo "k5-evidence: step $name exited $rc, expected $want (see $EV/logs/$name.stderr)" >&2
		exit 1
	fi
}
compress() { # results directory → results.jsonl replaced by results.jsonl.zst
	local f=$1/results.jsonl
	[ -f "$f" ] || return 0
	zstd -q -19 --rm -f "$f" -o "$f.zst"
}

setup() {
	# Binaries first: the precondition's cpgate is this commit's.
	step 0 build make build
	step 0 k5-precondition scripts/k5-precondition.sh
	step 0 gencorpus-k5-verify go run ./internal/tools/gencorpus --set k5 --verify --out testdata
	step 0 gencorpus-k2-verify go run ./internal/tools/gencorpus --verify --out testdata
	step 0 corpus-k5 bin/cpcheck corpus testdata/corpus-k5 --results-only --out "$EV/corpus"
	compress "$EV/corpus"
	# The K2 corpus with the K5 checkers: the completions change no K2
	# classification (ADR-0030).
	step 0 corpus-k2 bin/cpcheck corpus testdata/corpus --results-only --out "$EV/k2-corpus"
	compress "$EV/k2-corpus"
	for rule in $(go run ./internal/tools/k2check --set k5 --list-rules); do
		step 1 "sabotage-$rule" scripts/sabotage-corpus.sh "$rule" testdata/corpus-k5 "$EV/sabotage/$rule"
		compress "$EV/sabotage/$rule"
	done
	step 0 no-sabotage-symbols go test -count=1 -v -run '^TestProductBinariesHaveNoSabotage$' ./internal/independence
}

images() {
	# The binaries of this commit first: the runner image carries them.
	[ -n "$(recorded images-build)" ] || step 0 "$(next build)" make build
	step 0 images-build bin/commitproof images build
	step 0 images-verify bin/commitproof images verify
	for m in M3 M5; do step 0 "images-build-$m" bin/commitproof images build --mutant "$m"; done
}

rebuild() {
	local n=2
	while [ -n "$(recorded "build-$n")" ] || interrupted "build-$n"; do n=$((n + 1)); done
	step 0 "build-$n" make build
	step 0 "images-build-$n" bin/commitproof images build
	step 0 "images-verify-$n" bin/commitproof images verify
}

campaign() {
	local n=1 prev
	while :; do
		prev=$(recorded "campaign-k5-$n")
		case "$prev" in
		"")
			interrupted "campaign-k5-$n" || break
			echo "== campaign-k5-$n was interrupted (logs, no record); resuming as the next attempt" >&2
			n=$((n + 1)) ;;
		0 | 1) echo "== campaign complete (campaign-k5-$n exit $prev)" >&2; return 0 ;;
		*) n=$((n + 1)) ;;
		esac
	done
	step any "campaign-k5-$n" bin/commitproof campaign --matrix campaigns/k5.json --out "$EV/runs"
	prev=$(recorded "campaign-k5-$n")
	[ "$prev" = 0 ] || [ "$prev" = 1 ] || { echo "k5-evidence: campaign-k5-$n exit $prev; re-run to resume" >&2; exit 1; }
}

d3p() {
	# The predictions must be committed before any D3′ run (ADR-0033).
	git ls-files --error-unmatch "$EV/predictions-D3p.md" >/dev/null 2>&1 ||
		{ echo "k5-evidence: $EV/predictions-D3p.md is not committed" >&2; exit 1; }
	local n=1 name=campaign-k5-d3p prev
	while :; do
		prev=$(recorded "$name")
		case "$prev" in
		"")
			interrupted "$name" || break
			echo "== $name was interrupted (logs, no record); resuming as the next attempt" >&2 ;;
		0 | 1) echo "== D3′ campaign complete ($name exit $prev)" >&2; return 0 ;;
		esac
		n=$((n + 1)) name=campaign-k5-d3p-$n
	done
	step any "$name" bin/commitproof campaign --matrix campaigns/k5-d3p.json --out "$EV/runs"
	prev=$(recorded "$name")
	[ "$prev" = 0 ] || [ "$prev" = 1 ] || { echo "k5-evidence: $name exit $prev; re-run to resume" >&2; exit 1; }
}

oracle() {
	# Real-build primary runs that FAIL with C3 anomalies get the elle-cli
	# cross-check (§10.11; K5.5 as K4.7); cpcheck rewrites their checks.json.
	for c in "$EV"/runs/*.checks.json; do
		d=${c%.checks.json}
		[ -d "$d" ] || continue
		grep -q '"mutant":"real"' "$d/manifest.json" || continue
		grep -q '"replay_of"\|"candidate_of"' "$d/manifest.json" && continue
		grep -q '"verdict":"FAIL"' "$c" || continue
		python3 -c "import json,sys; c=json.load(open(sys.argv[1])); sys.exit(0 if any(x['id']=='C3' and x['valid'] is False for x in c['checkers']) else 1)" "$c" || continue
		step any "oracle-$(basename "$d")" bin/cpcheck check "$d" --elle-oracle
		# As K4: when cpcheck's three elle-cli passes cannot finish, the
		# validity pass is recorded on its own (and the process pass, to show
		# the failure).
		if [ "$(recorded "oracle-$(basename "$d")")" != 1 ] && [ -f "$d.elle/history.elle.json" ]; then
			iso=$(grep -o '"iso":"[a-z-]*"' "$d/plan.json" | sort -u | sed 's/.*:"\(.*\)"/\1/')
			model=serializable
			[ "$iso" = repeatable-read ] && model=snapshot-isolation
			step any "elle-validity-$(basename "$d")" docker run --rm --label com.docker.compose.project=commitproof --network none \
				--read-only --tmpfs /tmp -v "./$d.elle:/h:ro" commitproof/elle-oracle:9c2a18b -m list-append -c "$model" \
				--output json --cycle-search-timeout 10000 /h/history.elle.json
			step any "elle-process-$(basename "$d")" docker run --rm --label com.docker.compose.project=commitproof --network none \
				--read-only --tmpfs /tmp -v "./$d.elle:/h:ro" commitproof/elle-oracle:9c2a18b -m list-append -c "$model" \
				--output json --cycle-search-timeout 10000 \
				-a G0,G1a,G1b,G1c,G-single,G-nonadjacent,G2-item,incompatible-order,dirty-update,G0-process,G1c-process,G-single-process,G-nonadjacent-process,G2-item-process \
				/h/history.elle.json
		fi
	done
}

analysis() {
	local dirs=() d
	for d in "$EV"/runs/*/; do
		d=${d%/}
		[ -f "$d/seal.json" ] || continue
		grep -q '"replay_of"\|"candidate_of"' "$d/manifest.json" && continue
		dirs+=("$d")
	done
	[ "${#dirs[@]}" -gt 0 ] || { echo "k5-evidence: no primary run directories to analyse" >&2; return 0; }
	local name
	for name in k3obs k5obs; do
		step 0 "$(next "$name")" go run "./internal/tools/$name" "${dirs[@]}"
	done
}

ci() {
	step 0 lint-workflow make lint-workflow
	# A failed attempt stays recorded; the next one is ci-<n> (K5.6 reads the
	# latest attempt). A passed attempt is current until the binaries are
	# rebuilt (a later build or build-<n> record).
	local last
	last=$(grep -oE '"name":"ci(-[0-9]+)?"' "$EV/commands.jsonl" 2>/dev/null | tail -n 1 | cut -d'"' -f4)
	if [ -n "$last" ] && [ "$(recorded "$last")" = 0 ] && [ "$(line "$last")" -gt "$(line 'build(-[0-9]+)?')" ]; then
		echo "== skip $last (recorded, exit 0, after the last build)" >&2
		return 0
	fi
	step 0 "$(next ci)" make ci-unit ci-checkers ci-cluster-smoke ci-nemesis-smoke ci-mutant-smoke
}

store() {
	if [ -z "$(recorded store-runs)" ] || [ -n "$(rundirs)" ]; then
		step 0 "$(next store-runs)" scripts/k5-store-runs.sh "$EV/runs" runs/k5-full "${K5_STORE_POLICY:-adr0030}"
		mkdir -p "$EV/mutants"
		for m in M3 M5; do cp "mutants/$m.patch" "$EV/mutants/$m.patch"; done
		cp images.lock.json "$EV/images.lock.json"
		step 0 "$(next results)" go run ./internal/tools/k5results --runs "$EV/runs" --out "$EV/results.json"
	else
		echo "== skip store (no new run directories)" >&2
	fi
}

gate() {
	"${REC[@]}" "$(next cpgate-k5)" -- bin/cpgate K5 --evidence "$EV" --negative-controls
}

case "${1:-}" in
setup) setup ;;
images) images ;;
rebuild) rebuild ;;
campaign) campaign ;;
d3p) d3p ;;
oracle) oracle ;;
analysis) analysis ;;
ci) ci ;;
store) store ;;
gate) gate ;;
*) echo "usage: $0 setup|images|rebuild|campaign|d3p|oracle|analysis|ci|store|gate" >&2; exit 3 ;;
esac
