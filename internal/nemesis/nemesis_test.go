func TestLeaderOf(t *testing.T) {
	r := &ruleObs{CoordinatorTerm: 2, LeaderSubterm: 0, Leader: "n2", Cohort: []string{"n1", "n2", "n3"}}
	sts := []statusObs{
		{Node: "n1", OK: true, Name: "n1", Decision: r},
		{Node: "n2", OK: true, Name: "n2", Decision: r},
		{Node: "n3", OK: false},
	}
	l, rule, claims, err := leaderOf(sts)
	if err != nil || l != "n2" || rule.key() != "2.0" || len(claims) != 1 {
		t.Fatalf("leader %q %v %v %v", l, rule, claims, err)
	}
	// n1 still reports itself leader of the older rule 1.0: superseded by
	// n2's 2.0 (the K3 F2a observation).
	sts[0].Decision = &ruleObs{CoordinatorTerm: 1, Leader: "n1", Cohort: []string{"n1", "n2", "n3"}}
	l, _, claims, err = leaderOf(sts)
	if err != nil || l != "n2" || strings.Join(claims, ",") != "n1@1.0,n2@2.0" {
		t.Fatalf("superseded leader: %q %v %v", l, claims, err)
	}
	// Two nodes claiming the same highest rule number: ambiguous.
	sts[0].Decision = &ruleObs{CoordinatorTerm: 2, Leader: "n1"}
	if _, _, _, err := leaderOf(sts); err == nil {
		t.Fatal("tie resolved")
	}
	if _, _, _, err := leaderOf([]statusObs{{Node: "n1", OK: false}}); err == nil {
		t.Fatal("no leader resolved")
	}
	if (&ruleObs{CoordinatorTerm: 1, LeaderSubterm: 5}).after(&ruleObs{CoordinatorTerm: 2}) {
		t.Fatal("rule order")
	}
}

func testView() view {
	running := map[string]bool{}
	for _, c := range []string{"pg-n1", "pg-n2", "pg-n3", "pooler-n1", "pooler-n2", "pooler-n3", "etcd",
		"orch-z1", "orch-z2", "orch-z3", "gw-z1", "gw-z2", "gw-z3"} {
		running[Container(c)] = true
	}
	running[RunnerContainer], running[NemRunner] = true, true
	return view{running: running, nodes: []string{"n1", "n2", "n3"}, leader: "n1", leaderOK: true,
		rule: &ruleObs{Leader: "n1", Cohort: []string{"n1", "n2", "n3"}}}
}

func TestRoleResolution(t *testing.T) {
	v := testView()
	cases := []struct{ role, want string }{
		{"leader", "n1"}, {"n3", "n3"}, {"etcd", "etcd"}, {"runner", "runner"},
	}
	for _, c := range cases {
		if got, err := v.netns(c.role, 0); err != nil || got != c.want {
			t.Errorf("netns(%s) = %q %v", c.role, got, err)
		}
	}
	// random-follower: followers sorted [n2 n3], pick mod 2.
	if got, _ := v.node("random-follower", 7); got != "n3" {
		t.Errorf("random-follower pick 7 = %s, want n3", got)
	}
	if got, _ := v.netns("random-gw", 4); got != "gw-z2" {
		t.Errorf("random-gw pick 4 = %s, want gw-z2", got)
	}
	if got, _ := v.service("pooler:leader", 0); got != "pooler-n1" {
		t.Errorf("pooler:leader = %s", got)
	}
	if _, err := v.node("n4", 0); err == nil {
		t.Error("n4 resolved while not running")
	}
	if RunningNamespaces(v.running)[0] != "etcd" || len(RunningNamespaces(v.running)) != 11 {
		t.Errorf("running namespaces %v", RunningNamespaces(v.running))
	}
}

func pairSet(ps [][2]string) []string {
	var out []string
	for _, p := range ps {
		out = append(out, p[0]+">"+p[1])
	}
	sort.Strings(out)
	return out
}

func TestPartitionShapes(t *testing.T) {
	e := &Env{Prefix: "10.77.0"}
	running := []string{"etcd", "gw-z1", "n1", "n2", "orch-z1", "runner"}
	// F1a on n1: cut from the five others, both directions, rules in all six.
	p := isolate(e, "f0", "n1", running)
	if len(p.fail) != 10 || len(p.ok) != 0 || len(p.rules) != 6 {
		t.Fatalf("F1a: %d fail, %d ok, %d namespaces", len(p.fail), len(p.ok), len(p.rules))
	}
	if r := p.rules["n1"]; len(r.DropOut) != 5 || len(r.DropIn) != 5 {
		t.Fatalf("F1a target rules %+v", r)
	}
	if r := p.rules["etcd"]; !reflect.DeepEqual(r.DropOut, []string{"n1"}) || !reflect.DeepEqual(r.DropIn, []string{"n1"}) {
		t.Fatalf("F1a peer rules %+v", r)
	}
	// F1b {n1, orch-z1} | {n2, etcd}: 2×2 pairs cut both ways; A–A and B–B must connect.
	p = split(e, "f1", []string{"n1", "orch-z1"}, []string{"n2", "etcd"})
	if got := pairSet(p.ok); !reflect.DeepEqual(got, []string{"etcd>n2", "n1>orch-z1", "n2>etcd", "orch-z1>n1"}) {
		t.Fatalf("F1b ok pairs %v", got)
	}
	if len(p.fail) != 8 {
		t.Fatalf("F1b fail pairs %v", pairSet(p.fail))
	}
	// F1c on n1: cut from etcd, n2, orch-z1; gw-z1 connects both ways; runner untouched.
	p = asymmetric(e, "f2", "n1", running)
	if got := pairSet(p.ok); !reflect.DeepEqual(got, []string{"gw-z1>n1", "n1>gw-z1"}) {
		t.Fatalf("F1c ok %v", got)
	}
	if _, ok := p.rules["runner"]; ok || len(p.fail) != 6 {
		t.Fatalf("F1c fail %v rules %v", pairSet(p.fail), p.rules)
	}
	// F1d: rules only on the leader, OUTPUT drops and SYN counters.
	p = oneWay(e, "f3", "n1", []string{"n2", "n3"})
	if len(p.rules) != 1 || !reflect.DeepEqual(p.rules["n1"].DropOut, []string{"n2", "n3"}) || len(p.rules["n1"].DropIn) != 0 ||
		!reflect.DeepEqual(p.rules["n1"].CountIn, []string{"n2", "n3"}) {
		t.Fatalf("F1d rules %+v", p.rules["n1"])
	}
	o, i := oneWay(e, "f2.1", "n1", nil).chains()
	if o != "CPN-f2_1-O" || i != "CPN-f2_1-I" {
		t.Fatalf("chains %s %s", o, i)
	}
}

func TestIptablesSaveCounters(t *testing.T) {
	out := `# Generated by iptables-save v1.8.13 (nf_tables)
*filter
:INPUT ACCEPT [0:0]
[7:420] -A INPUT -j CPN-f0-I
[3:180] -A CPN-f0-O -d 10.77.0.12/32 -j DROP
[0:0] -A CPN-f0-O -d 10.77.0.13/32 -j DROP
[2:120] -A CPN-f0-I -s 10.77.0.12/32 -p tcp -m tcp --tcp-flags FIN,SYN,RST,ACK SYN
COMMIT`
	cs := parseSave(out)
	if len(cs) != 4 {
		t.Fatalf("%d rules", len(cs))
	}
	if n := packets(cs, "CPN-f0-O", "-d", "10.77.0.12", false); n != 3 {
		t.Errorf("drop to .12: %d", n)
	}
	if n := packets(cs, "CPN-f0-O", "-d", "10.77.0.13", false); n != 0 {
		t.Errorf("drop to .13: %d", n)
	}
	if n := packets(cs, "CPN-f0-I", "-s", "10.77.0.12", true); n != 2 {
		t.Errorf("syn from .12: %d", n)
	}
	if n := packets(cs, "CPN-f0-O", "-d", "10.77.0.14", false); n != -1 {
		t.Errorf("absent rule: %d", n)
	}
}

